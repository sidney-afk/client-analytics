'use strict';
/*
 * Writes one tiny stub page per top-level clean path (/synclinear.html,
 * /calendar.html, ...), so GitHub Pages answers those addresses with a real
 * 200 page instead of the 404 fallback. Each stub hands off to the app at
 * /?sv_path=<path>, and the app puts the clean path back in the address bar
 * (src/index/003-sv-route.html.part). The list of pages comes from that
 * file's TOP list, so the stubs cannot drift from the router.
 *
 *   node scripts/build-route-stubs.js          write the stubs
 *   node scripts/build-route-stubs.js --check  fail if any stub is missing or stale
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');

function routeTable() {
  const src = fs.readFileSync(path.join(ROOT, 'src/index/003-sv-route.html.part'), 'utf8');
  const body = src.replace(/^\s*<script>/, '').replace(/<\/script>\s*$/, '');
  const noop = () => {};
  const ctx = {
    URL, URLSearchParams,
    location: { pathname: '/', search: '', hash: '', origin: 'https://example.invalid' },
    history: { state: null, pushState: noop, replaceState: noop },
    window: { addEventListener: noop },
  };
  vm.createContext(ctx);
  vm.runInContext(body, ctx);
  return ctx.window.svRoute;
}

function stubHtml(name) {
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>SyncView</title>
<!-- Generated by scripts/build-route-stubs.js for /${name}. Do not edit. -->
<script>location.replace('/?sv_path=' + encodeURIComponent(location.pathname) + location.search.replace(/^\\?/, '&') + location.hash);</script>
</head>
<body style="background:#f4f4f2;font-family:system-ui,sans-serif"><noscript><a href="/">Open SyncView</a></noscript></body>
</html>
`;
}

function main() {
  const check = process.argv.includes('--check');
  const { TOP } = routeTable();
  const problems = [];
  for (const name of TOP) {
    const file = path.join(ROOT, name + '.html');
    const want = stubHtml(name);
    const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (have === want) continue;
    if (check) problems.push(name + '.html');
    else fs.writeFileSync(file, want);
  }
  if (problems.length) {
    console.error('route stubs missing or stale: ' + problems.join(', ') + '\nRun: node scripts/build-route-stubs.js');
    process.exit(1);
  }
  console.log(`route stubs ${check ? 'checked' : 'written'}: ${TOP.length}`);
}

if (require.main === module) main();
module.exports = { routeTable, stubHtml };
