/*
 * Owner-dispatched Slice 5 TEST drills (all six in SLICE5_APPLY_WINDOW.md §3).
 *
 * This file is inert when imported. A run requires the exact opt-in value
 * SLICE5_TEST_DRILLS_CONFIRM=SLICE5_TEST_ONLY plus service, Linear, and all
 * three staff-role credentials. Runtime flags are read before/after and are
 * never written.
 *
 * HARD SAFETY CONTRACT
 * --------------------
 * - The unique active `kind=test` client is discovered; no slug is accepted
 *   from workflow input or environment.
 * - Every network mutation goes through one of WRITE_ADAPTERS. Each adapter
 *   re-reads the unique active TEST client immediately before its fetch.
 * - Every mutable row is run-owned and carries the lowercase `drill` marker.
 * - team_members ids are generated by this run, checked absent before insert,
 *   recorded in an in-memory allowlist, and re-read/marker-checked before any
 *   PATCH or DELETE. A pre-existing member is never changed.
 * - Browser backend writes are blocked. The only browser POSTs allowed are
 *   guarded read/verifier couriers; role/service values are never installed in
 *   page JavaScript or localStorage.
 * - Public stdout/report values are enums, counts, and booleans only. Exact
 *   ids, names, URLs, responses, and failures stay in the optional private log
 *   whose path must resolve outside this repository.
 */

