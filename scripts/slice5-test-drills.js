function forceKillBrowserServer(server) {
  let killPromise = Promise.resolve();
  try {
    killPromise = Promise.resolve(server.kill());
  } catch (_) {}
  try {
    const child = typeof server.process === 'function' ? server.process() : null;
    if (child && child.exitCode == null && child.signalCode == null) child.kill('SIGKILL');
  } catch (_) {}
  return killPromise.catch(() => {});
}

function neutralizeStaticServer(server) {
  try { server.unref(); } catch (_) {}
  const closed = new Promise((resolve, reject) => {
    try {
      server.close(error => {
        if (error && error.code !== 'ERR_SERVER_NOT_RUNNING') reject(error);
        else resolve();
      });
    } catch (error) {
      if (error && error.code === 'ERR_SERVER_NOT_RUNNING') resolve();
      else reject(error);
    }
  });
  // close() stops new accepts before the force-close sweep, eliminating the
  // race where a new keep-alive connection appears after the sweep.
  try {
    if (typeof server.closeIdleConnections === 'function') server.closeIdleConnections();
  } catch (_) {}
  try {
    if (typeof server.closeAllConnections === 'function') server.closeAllConnections();
  } catch (_) {}
  return closed;
}

