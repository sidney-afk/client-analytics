async function linearRead(runtime, query, variables = {}, stage = 'preflight') {
  assert(/^\s*query\b/.test(clean(query)), stage,
    'Linear read helper refuses non-query GraphQL documents', undefined, 'linear_query_not_read_only');
  const { response, bytes } = await liveRequest(runtime, LINEAR_URL, {
    method: 'POST',
    headers: {
      Authorization: runtime.config.linearKey,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ query, variables }),
  }, {
    stage,
    kind: 'linear_read',
  });
  const body = responseBody(bytes);
  if (!response.ok || !body || body.errors) {
    // One code for three unrelated failures made this undebuggable: a bad key,
    // a rate limit and an invalid query need three different fixes and looked
    // identical. Split by the class of failure, and carry the numeric HTTP
    // status -- which names the class without describing any client, issue,
    // project or response body. The status and the GraphQL errors themselves
    // continue to go only to the private log, which is unchanged and still
    // never uploaded.
    const status = Number(response.status) || 0;
    const code = status === 401 || status === 403
      ? 'linear_auth_failed'
      : status === 429
        ? 'linear_rate_limited'
        : (response.ok && body && body.errors)
          ? 'linear_query_rejected'
          : 'linear_read_failed';
    fail(stage, 'Linear read failed',
      { status: response.status, errors: body && body.errors }, code, status);
  }
  return body.data;
}

// The failure code is REQUIRED and positional, ahead of the predicate. A poll
// that runs out of patience is the one failure whose message says nothing
// useful in public -- every wait names the exact thing it was waiting for.
async function poll(runtime, stage, label, code, fn, timeoutMs = 60_000, intervalMs = 750) {
  assert(FAILURE_CODES.has(code), stage,
    'poll was called without an allowlisted timeout code', { label }, 'poll_code_missing');
  const deadline = Date.now() + timeoutMs;
  let last = null;
  while (Date.now() < deadline) {
    const remaining = Math.max(1, deadline - Date.now());
    last = await boundedOperation(runtime, stage, label, fn, remaining);
    if (last) return last;
    await sleep(Math.min(intervalMs, Math.max(1, deadline - Date.now())));
  }
  fail(stage, `${label} timed out`, { last }, code);
}

/* Read a batch's PARENT-ISSUE linkage out of linear_parent_ids.

   Derived from mergeBatchParentIds (supabase/functions/linear-outbound/
   mapping.mjs), which is the only writer of that column. It ends with:

     parents[parentTeamKey(team)] = { uuid, identifier, url }

   Three properties of that writer this reader mirrors:

   1. The stored value is a TEAM-KEYED OBJECT, and the key is normalized by
      parentTeamKey: gra/graphic/graphics -> 'graphics', everything else ->
      'video'. Matching the raw team string would miss a 'GRA' or 'VID' key.
   2. The issue id is under `uuid`. mergeBatchParentIds ACCEPTS id and
      linear_issue_id on its array input, but the only key it ever EMITS for
      the team it writes is `uuid`.
   3. Its object branch copies teams it is not writing straight through with
      `{ ...value }`, so an entry stored before that normalization can survive
      carrying `id` or `linear_issue_id` and no `uuid`. That, and only that, is
      why the two fallbacks below exist -- they are not speculative tolerance.

   The array branch mirrors the array input mergeBatchParentIds itself accepts,
   for rows written before it normalized them to an object.

   This is deliberately NOT projectIdsForTeam. That reads
   clients.linear_project_ids, a PROJECT-id map keyed id/project_id/
   linear_project_id. linear_parent_ids is parent-ISSUE linkage with a
   different schema and a different writer; the two are unrelated. */
function parentTeamKey(value) {
  const key = lower(value);
  return key === 'gra' || key === 'graphic' || key === 'graphics'
    ? 'graphics'
    : 'video';
}

function parentIssueIdsForTeam(value, wantedTeam) {
  let parsed = value;
  if (typeof parsed === 'string') {
    try { parsed = JSON.parse(parsed); } catch (_) { parsed = {}; }
  }
  const wanted = parentTeamKey(wantedTeam);
  const found = new Set();
  const idFrom = entry => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return '';
    return clean(entry.uuid) || clean(entry.id) || clean(entry.linear_issue_id);
  };
  if (Array.isArray(parsed)) {
    for (const entry of parsed) {
      if (!entry || typeof entry !== 'object') continue;
      if (parentTeamKey(entry.team || entry.team_key || entry.key) !== wanted) continue;
      const id = idFrom(entry);
      if (id) found.add(id);
    }
  } else if (parsed && typeof parsed === 'object') {
    for (const [key, entry] of Object.entries(parsed)) {
      if (parentTeamKey(key) !== wanted) continue;
      const id = idFrom(entry);
      if (id) found.add(id);
    }
  }
  return [...found].sort();
}

function projectIdsForTeam(value, wantedTeam) {
  const wanted = lower(wantedTeam);
  const found = new Set();
  const idsFrom = entry => {
    if (typeof entry === 'string' && clean(entry)) return [clean(entry)];
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return [];
    return ['id', 'project_id', 'linear_project_id'].map(key => clean(entry[key])).filter(Boolean);
  };
  const addExplicit = entry => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return;
    const team = lower(entry.team || entry.team_key || entry.key || entry.kind);
    if (team === wanted) idsFrom(entry).forEach(id => found.add(id));
  };
  if (Array.isArray(value)) value.forEach(addExplicit);
  else if (value && typeof value === 'object') {
    for (const [key, entry] of Object.entries(value)) {
      if (lower(key) === wanted) idsFrom(entry).forEach(id => found.add(id));
    }
    addExplicit(value);
    if (Array.isArray(value.projects)) value.projects.forEach(addExplicit);
  }
  return [...found].sort();
}

/* The client-row project ids as a FLAT set, mirroring b4-write projectIds — the
   rule the TEST-override check on the drill's own create path actually applies.
   Deliberately separate from projectIdsForTeam, which requires a team-tagged
   entry and is left untouched because the real-client intake path still depends
   on that stricter shape.

   Mirrors b4-write exactly, INCLUDING its blind spot: it descends into array
   children only, so a team-keyed object such as {"video": "<id>"} yields []. */
function flatClientProjectIds(value) {
  const ids = new Set();
  const stack = Array.isArray(value) ? [...value] : (value ? [value] : []);
  while (stack.length) {
    const item = stack.pop();
    if (typeof item === 'string' && clean(item)) ids.add(clean(item));
    else if (item && typeof item === 'object') {
      for (const key of ['id', 'project_id', 'linear_project_id']) {
        if (clean(item[key])) ids.add(clean(item[key]));
      }
      for (const child of Object.values(item)) if (Array.isArray(child)) stack.push(...child);
    }
  }
  return [...ids].sort();
}

