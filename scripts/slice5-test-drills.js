    matrixWrites: 0,
    matrixPolicyWrites: 0,
    matrixCasWrites: 0,
    matrixSequence: 0,
    matrixExpected: null,
    lastMatrixResponse: null,
    matrixRequestIds,
    matrixSyntheticStamp: matrixSyntheticStamp(0),
    routeError: null,
