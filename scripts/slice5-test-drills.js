async function browserProjection(runtime, url, routeState) {
  const table = url.pathname.split('/rest/v1/')[1] || '';
  if (table === 'clients') {
    return restRead(runtime,
      `clients?select=slug,display_name,active,kind,emoji,board_status,lead_member_id,target_date,board_desc,linear_project_ids,updated_at&slug=eq.${encodeURIComponent(runtime.client.slug)}`);
  }
  if (table === 'team_members') {
    const ids = [...runtime.createdMemberIds];
    if (!ids.length) return [];
    const activeOnly = url.searchParams.get('active') === 'eq.true';
    const rows = await restRead(runtime,
      `team_members?select=id,name,email,role,team,avatar_color,active&id=in.(${ids.map(encodeURIComponent).join(',')})&order=name.asc`);
    const filtered = activeOnly ? rows.filter(row => row.active === true) : rows;
    return routeState.reverseMembers ? [...filtered].reverse() : filtered;
  }
  if (table === 'batches') {
    const ids = [...runtime.createdBatchIds];
    if (!ids.length) return [];
    return restRead(runtime,
      `batches?select=*&id=in.(${ids.map(encodeURIComponent).join(',')})&client_slug=eq.${encodeURIComponent(runtime.client.slug)}&order=created_at.desc`);
  }
  if (table === 'production_deliverables_browser_v1') {
    if (routeState.failDelta === true && url.searchParams.has('updated_at')) {
      return { __forcedStatus: 503 };
    }
    const ids = [...runtime.createdDeliverableIds];
    if (!ids.length) return [];
    const select = clean(url.searchParams.get('select')) || '*';
    const filters = [
      `select=${encodeURIComponent(select)}`,
      `id=in.(${ids.map(encodeURIComponent).join(',')})`,
      `client_slug=eq.${encodeURIComponent(runtime.client.slug)}`,
      'order=id.asc',
    ];
    const watermark = clean(url.searchParams.get('updated_at'));
    if (watermark) filters.push(`updated_at=${encodeURIComponent(watermark)}`);
    return restRead(runtime,
      `production_deliverables_browser_v1?${filters.join('&')}`,
      { stage: routeState.stage || 'f95_convergence' });
  }
  if (table === 'deliverable_events') {
    return restRead(runtime,
      `deliverable_events?select=id,deliverable_id,batch_id,client_slug,ts,actor,role,action,from_status,to_status,source,payload&deliverable_id=eq.${encodeURIComponent(runtime.fixture.deliverableId)}&order=ts.desc&limit=30`,
      { stage: routeState.stage || 'f95_convergence' });
  }
  if (table === 'syncview_runtime_flags') {
    const query = url.searchParams.toString();
    return restRead(runtime, `syncview_runtime_flags?${query}`,
      { stage: routeState.stage || 'f95_convergence' });
  }
  // The local browser is a TEST-only projection. An unknown table never falls
  // through to a live full-roster/full-client read.
  return [];
}

async function installBrowserRoutes(runtime, context, routeState) {
  await context.route('**/*', async route => {
    const request = route.request();
    const url = new URL(request.url());
    const method = request.method().toUpperCase();
    try {
      const isSupabase = url.origin === runtime.config.supabaseUrl;
      if (method === 'OPTIONS' && isSupabase) {
        await route.fulfill({
          status: 204,
          headers: {
            'Access-Control-Allow-Origin': '*',
            'Access-Control-Allow-Methods': 'GET,HEAD,POST,OPTIONS',
            'Access-Control-Allow-Headers':
              request.headers()['access-control-request-headers']
              || 'authorization,apikey,content-type,x-syncview-actor,x-syncview-key,x-syncview-role',
          },
          body: '',
        });
        return;
      }
      if ((method === 'GET' || method === 'HEAD')
          && isSupabase && url.pathname.includes('/rest/v1/')) {
        const body = await browserProjection(runtime, url, routeState);
        if (body && body.__forcedStatus) {
          await route.fulfill({
            status: body.__forcedStatus,
            contentType: 'application/json',
            headers: { 'Access-Control-Allow-Origin': '*' },
            body: JSON.stringify({ error: 'forced_drill_failure' }),
          });
          return;
        }
        await route.fulfill({
          status: 200,
          contentType: 'application/json',
          headers: {
            'Access-Control-Allow-Origin': '*',
            'Cache-Control': 'no-store',
          },
          body: JSON.stringify(body),
        });
        return;
      }
      if (method === 'POST' && isSupabase && url.pathname === '/functions/v1/key-verify') {
        const input = parseJson(request.postData());
        const memberId = clean(parseJson(input.member).id);
        const result = await guardedBrowserVerifier(
          runtime,
          request,
          roleKeyForMember(runtime, memberId),
          {
            targetClientSlug: runtime.client.slug,
            stage: routeState.stage || 'f37_identity',
          },
        );
        await route.fulfill(result);
        return;
      }
      if (method === 'POST' && isSupabase && url.pathname === '/functions/v1/production-write') {
        const input = parseJson(request.postData());
        const action = lower(input.action);
        const operation = lower(input.operation);
        if (['labels_read', 'asset_access_read', 'description_read'].includes(action)) {
          // Direct-detail boot may ask for optional protected panels. They are
          // outside this drill and are blocked locally; no live provider probe
          // or access-check write is allowed to escape the browser.
          await route.abort('blockedbyclient');
          return;
        }
        if (routeState.allowMatrix === true) {
          const actor = routeState.matrixActor;
          assert(actor
              && operation === 'status'
              && !input.test_override
              && !input.confirm
              && clean(input.id) === runtime.fixture.deliverableId
              && runtime.policy.DELIVERABLE_STATUSES.includes(lower(input.status))
              && runtime.policy.DELIVERABLE_STATUSES.includes(lower(input.expected_status))
              && clean(input.expected_updated_at) === '1970-01-01T00:00:00.000Z'
              && clean(request.headers()['x-syncview-actor']) === clean(actor.name)
              && lower(request.headers()['x-syncview-role']) === lower(actor.role),
          'f136_matrix', 'browser matrix request is outside the exact TEST oracle allowlist');
          const result = await gatewayWrite(runtime, input, {
            staff: actor,
            actorMemberId: actor.id,
            targetClientSlug: runtime.client.slug,
            stage: 'f136_matrix',
          });
          routeState.matrixWrites = Number(routeState.matrixWrites || 0) + 1;
          await route.fulfill({
            status: result.status,
            contentType: 'application/json',
            headers: { 'Access-Control-Allow-Origin': '*' },
            body: JSON.stringify(result.body || {}),
          });
          return;
        }
        assert(routeState.allowAssigneePicker === true,
          routeState.stage || 'f94_stale_picker',
          'browser production-write is not enabled for this drill');
        assert(clean(input.id) === runtime.fixture.deliverableId
            && ((action === 'assignee_options'
                && clean(input.client_slug) === runtime.client.slug)
              || (operation === 'assignee'
                && runtime.createdMemberIds.has(clean(input.assignee_id)))),
        'f94_stale_picker',
        'browser production-write is outside the exact stale-picker allowlist');
        // The page performs the real picker interaction, but the intercepted
        // request is couriered through the service-only TEST override. No staff
        // credential or service value enters page JavaScript.
        const result = await gatewayWrite(runtime, gatewayServiceBody(runtime, input), {
          targetClientSlug: runtime.client.slug,
          stage: 'f94_stale_picker',
        });
        routeState.lastProductionWrite = {
          action: action || operation,
          status: result.status,
          code: clean(result.body && result.body.error),
        };
        await route.fulfill({
          status: result.status,
          contentType: 'application/json',
          headers: { 'Access-Control-Allow-Origin': '*' },
          body: JSON.stringify(result.body || {}),
        });
        return;
      }
      if (method === 'POST' && isSupabase && url.pathname === '/functions/v1/production-comments') {
        if (routeState.stage === 'f136_matrix') {
          const input = parseJson(request.postData());
          assert(clean(input.deliverable_id) === runtime.fixture.deliverableId
              && Number(input.limit) > 0
              && Number(input.limit) <= 50,
          'f136_matrix', 'matrix browser comment read escaped the run-owned TEST fixture');
          await route.fulfill({
            status: 200,
            contentType: 'application/json',
            headers: { 'Access-Control-Allow-Origin': '*' },
            body: JSON.stringify({
              ok: true,
              canonical_thread: true,
              audience_scope: 'staff',
              comments: [],
              next_cursor: null,
              has_more: false,
            }),
          });
          return;
        }
        const result = await guardedBrowserCommentRead(runtime, request, {
          targetClientSlug: runtime.client.slug,
          stage: routeState.stage || 'f95_convergence',
        });
        await route.fulfill(result);
        return;
      }
      if (method === 'GET' || method === 'HEAD' || method === 'OPTIONS') {
        await route.continue();
        return;
      }
      // n8n/webhook/unknown-host writes are blocked as firmly as Supabase
      // writes; no browser mutation can escape through another origin.
      await route.abort('blockedbyclient');
    } catch (error) {
      routeState.routeError = error;
      await route.abort('failed').catch(() => {});
    }
  });
}

