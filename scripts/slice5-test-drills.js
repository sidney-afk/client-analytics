function responseBody(bytes) {
  const text = Buffer.isBuffer(bytes) ? bytes.toString('utf8') : clean(bytes);
  if (!text) return null;
  try { return JSON.parse(text); } catch (_) { return { _unparsed: true }; }
}

function requestDeadlineMs(
  runtime,
  requestedMs = LIVE_REQUEST_TIMEOUT_MS,
  now = Date.now(),
  stage = 'preflight',
) {
  const processDeadline = Number(runtime && runtime.processDeadlineAt);
  assert(Number.isFinite(processDeadline), 'preflight',
    'drill process deadline is unavailable', undefined, 'deadline_unresolved');
  if (runtime.cleanupStarted === true && !POST_CLEANUP_REQUEST_STAGES.has(stage)) {
    fail('cleanup', 'a non-cleanup request tried to start after cleanup began',
      undefined, 'request_after_cleanup');
  }
  const phaseDeadline = runtime.cleanupStarted === true
    ? processDeadline
    : processDeadline - CLEANUP_RESERVE_MS;
  const remaining = Math.floor(phaseDeadline - Number(now));
  assert(remaining > 0, runtime.cleanupStarted === true ? 'cleanup' : stage,
    runtime.cleanupStarted === true
      ? 'drill process deadline exhausted during cleanup'
      : 'drill phase exhausted the cleanup reserve', undefined, 'deadline_exhausted');
  return Math.max(1, Math.min(Number(requestedMs) || LIVE_REQUEST_TIMEOUT_MS, remaining));
}

async function liveRequest(runtime, url, init = {}, options = {}) {
  const stage = options.stage || 'preflight';
  const timeoutMs = requestDeadlineMs(runtime,
    options.timeoutMs || LIVE_REQUEST_TIMEOUT_MS, Date.now(), stage);
  const controller = new AbortController();
  let timedOut = false;
  const timer = setTimeout(() => {
    timedOut = true;
    controller.abort();
  }, timeoutMs);
  const upstreamSignal = init.signal;
  const abortFromUpstream = () => controller.abort();
  if (upstreamSignal) {
    if (upstreamSignal.aborted) controller.abort();
    else upstreamSignal.addEventListener('abort', abortFromUpstream, { once: true });
  }
  const activeControllers = runtime.activeRequestControllers instanceof Set
    ? runtime.activeRequestControllers
    : null;
  if (activeControllers) activeControllers.add(controller);
  try {
    const response = await runtime.fetch(url, {
      ...init,
      signal: controller.signal,
    });
    const bytes = typeof response.arrayBuffer === 'function'
      ? Buffer.from(await response.arrayBuffer())
      : Buffer.from(await response.text(), 'utf8');
    return { response, bytes };
  } catch (error) {
    fail(stage, timedOut ? 'live request exceeded its abort deadline' : 'live request failed', {
      request_kind: clean(options.kind || 'unknown'),
      timeout_ms: timeoutMs,
      aborted: controller.signal.aborted,
      error: error && error.message,
    }, 'live_request_failed');
  } finally {
    clearTimeout(timer);
    if (activeControllers) activeControllers.delete(controller);
    if (upstreamSignal) upstreamSignal.removeEventListener('abort', abortFromUpstream);
  }
}

async function boundedOperation(
  runtime,
  stage,
  label,
  operation,
  requestedMs = BROWSER_REQUEST_TIMEOUT_MS,
) {
  const timeoutMs = requestDeadlineMs(runtime, requestedMs, Date.now(), stage);
  const operationPromise = Promise.resolve().then(operation);
  const tracked = runtime.activeOperations instanceof Set && stage !== 'cleanup';
  if (tracked) {
    runtime.activeOperations.add(operationPromise);
    operationPromise.then(
      () => runtime.activeOperations.delete(operationPromise),
      () => runtime.activeOperations.delete(operationPromise),
    );
  }
  let timer = null;
  try {
    return await Promise.race([
      operationPromise,
      new Promise((_, reject) => {
        timer = setTimeout(() => {
          reject(new DrillError(stage, `${label} exceeded its deadline`, {
            timeout_ms: timeoutMs,
          }, 'bounded_operation_timeout'));
        }, timeoutMs);
      }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

async function acquireBoundedResource(
  runtime,
  stage,
  label,
  acquire,
  register,
  dispose,
  requestedMs = BROWSER_SETUP_TIMEOUT_MS,
) {
  const timeoutMs = requestDeadlineMs(runtime, requestedMs, Date.now(), stage);
  let expired = false;
  let timer = null;
  const acquisition = Promise.resolve().then(acquire).then(resource => {
    if (expired || runtime.cleanupStarted === true) {
      // Every resource disposer below neutralizes its handle synchronously
      // before returning a promise, so a late resolution cannot keep Node alive.
      Promise.resolve().then(() => dispose(resource)).catch(() => {});
      throw new DrillError(stage, `${label} resolved after its owner expired`,
        undefined, 'bounded_resource_expired');
    }
    try {
      register(resource);
    } catch (error) {
      Promise.resolve().then(() => dispose(resource)).catch(() => {});
      throw error;
    }
    return resource;
  });
  try {
    return await Promise.race([
      acquisition,
      new Promise((_, reject) => {
        timer = setTimeout(() => {
          expired = true;
          reject(new DrillError(stage, `${label} exceeded its acquisition deadline`, {
            timeout_ms: timeoutMs,
          }, 'bounded_resource_timeout'));
        }, timeoutMs);
      }),
    ]);
  } finally {
    if (timer) clearTimeout(timer);
  }
}

function abortActiveRequests(runtime) {
  const controllers = runtime.activeRequestControllers instanceof Set
    ? runtime.activeRequestControllers
    : [];
  for (const controller of controllers) {
    try { controller.abort(); } catch (_) {}
  }
}

async function runBoundedDrillPhase(runtime, stage, operation) {
  return boundedOperation(
    runtime,
    stage,
    `${stage} phase`,
    operation,
    DRILL_PROCESS_BUDGET_MS,
  );
}

async function restRead(runtime, resource, options = {}) {
  const stage = options.stage || 'preflight';
  const method = clean(options.method || 'GET').toUpperCase();
  assert(method === 'GET', stage,
    'Supabase read helper refuses mutation-capable HTTP methods',
    undefined, 'rest_read_method_forbidden');
  const { response, bytes } = await liveRequest(
    runtime,
    `${runtime.config.supabaseUrl}/rest/v1/${resource}`,
    {
    method,
    headers: {
      apikey: runtime.config.serviceKey,
      Authorization: `Bearer ${runtime.config.serviceKey}`,
      Accept: 'application/json',
      ...(options.headers || {}),
    },
    },
    {
      stage,
      kind: 'supabase_read',
    },
  );
  const body = responseBody(bytes);
  if (!response.ok) {
    fail(stage, 'Supabase read failed', {
      resource: resource.split('?')[0],
      status: response.status,
      body,
    }, 'supabase_read_failed');
  }
  return body;
}

