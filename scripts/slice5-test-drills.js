function sanitizePublicReport(value) {
  const template = emptyReport();
  const walk = (input, shape) => {
    if (typeof shape === 'boolean') {
      if (typeof input !== 'boolean') throw new Error('public report has invalid boolean');
      return input;
    }
    if (typeof shape === 'number') {
      if (!Number.isInteger(input) || input < 0) throw new Error('public report has invalid count');
      return input;
    }
    if (typeof shape === 'string') {
      if (typeof input !== 'string' || !PUBLIC_ENUMS.has(input)) {
        throw new Error('public report has non-enum string');
      }
      return input;
    }
    if (!input || typeof input !== 'object' || Array.isArray(input)) {
      throw new Error('public report has invalid object');
    }
    const inputKeys = Object.keys(input).sort();
    const shapeKeys = Object.keys(shape).sort();
    if (stableJson(inputKeys) !== stableJson(shapeKeys)) {
      throw new Error('public report has unknown or missing key');
    }
    return Object.fromEntries(Object.entries(shape)
      .map(([key, childShape]) => [key, walk(input[key], childShape)]));
  };
  return walk(value, template);
}

async function closeBrowsers(runtime) {
  abortActiveRequests(runtime);
  const failures = [];
  for (const context of [...runtime.contexts]) {
    try {
      await closeContext(runtime, context);
    } catch (error) {
      failures.push(error);
    }
  }
  for (const server of [...runtime.servers]) {
    try {
      await closeStaticServer(runtime, server);
    } catch (error) {
      failures.push(error);
    }
  }
  for (const browser of [...runtime.browsers]) {
    try {
      await boundedOperation(
        runtime, 'cleanup', 'browser close',
        () => browser.close(), RESOURCE_CLOSE_TIMEOUT_MS,
      );
      runtime.browsers.delete(browser);
    } catch (error) {
      failures.push(error);
    }
  }
  // launchServer gives cleanup a public process owner. kill() plus the child
  // signal neutralizes a browser even when Browser.close() or an earlier
  // context close never settled.
  for (const browserServer of [...runtime.browserServers]) {
    try {
      await boundedOperation(
        runtime,
        'cleanup',
        'Chromium server force kill',
        () => forceKillBrowserServer(browserServer),
        RESOURCE_CLOSE_TIMEOUT_MS,
      );
    } catch (error) {
      // forceKillBrowserServer sends the child signal synchronously before its
      // promise is awaited, so the process is neutralized even on timeout.
      failures.push(error);
    } finally {
      runtime.browserServers.delete(browserServer);
    }
  }
  runtime.contexts.clear();
  runtime.browsers.clear();

  const outstanding = runtime.activeOperations instanceof Set
    ? [...runtime.activeOperations]
    : [];
  if (outstanding.length) {
    try {
      await boundedOperation(
        runtime,
        'cleanup',
        'late browser operation drain',
        () => Promise.allSettled(outstanding),
        RESOURCE_CLOSE_TIMEOUT_MS,
      );
    } catch (error) {
      // All external handles are already unref'd, closed, or force-killed.
      // Retaining a bare unresolved promise cannot hold the Node process open.
      failures.push(error);
    } finally {
      runtime.activeOperations.clear();
    }
  }
  return failures;
}

async function main(env = process.env, deps = {}) {
  const config = parseConfig(env);
  const runtime = makeRuntime(config, deps);
  const report = emptyReport();
  let failure = null;
  let stage = 'preflight';
  let cleanupResult = { ok: false, deletedMembers: 0 };
  try {
    await runBoundedDrillPhase(runtime, 'preflight', async () => {
      await preflight(runtime);
      report.preflight.result = 'pass';
      // PREFLIGHT-ONLY MODE. Every preflight check above is a read; the first
      // write in this lane is reserveRunIdentities/openDurableRunLedger below.
      // Returning here is therefore structurally incapable of mutating: it is
      // placed before the first create, not merely guarding each one, so a
      // future create added to this phase cannot be reached either.
      if (runtime.config.preflightOnly) {
        report.preflight_only = true;
        return;
      }
      const identityPlan = await reserveRunIdentities(runtime);
      await openDurableRunLedger(runtime);
      report.created_member_count = await createSyntheticMembers(
        runtime, identityPlan.members,
      );
      await createFixture(runtime, identityPlan.fixture);
    });

    // A preflight-only dispatch exits successfully here: no drill stage runs, no
    // browser is launched, and nothing was created for cleanup to remove. Its
    // purpose is to turn precondition debugging into a 60-second run instead of
    // a 1-3 hour one.
    if (runtime.config.preflightOnly) {
      report.ok = true;
      report.error_code = 'none';
      report.failure_code = 'none';
      const preflightPublic = sanitizePublicReport(report);
      if (config.reportPath) {
        const output = path.resolve(config.reportPath);
        fs.mkdirSync(path.dirname(output), { recursive: true });
        fs.writeFileSync(output, JSON.stringify(preflightPublic, null, 2));
      }
      process.stdout.write(`${JSON.stringify(preflightPublic)}\n`);
      return preflightPublic;
    }

    stage = 'f94_negative';
    report.f94_negative = await runBoundedDrillPhase(
      runtime, stage, () => runF94Negative(runtime),
    );
    stage = 'f94_stale_picker';
    report.f94_stale_picker = await runBoundedDrillPhase(
      runtime, stage, () => runF94StalePicker(runtime),
    );
    stage = 'f136_matrix';
    report.f136_matrix = await runBoundedDrillPhase(
      runtime, stage, () => runF136Matrix(runtime),
    );
    stage = 'f37_identity';
    report.f37_identity = await runBoundedDrillPhase(
      runtime, stage, () => runF37Identity(runtime),
    );
    stage = 'f95_convergence';
    report.f95_convergence = await runBoundedDrillPhase(
      runtime, stage, () => runF95Convergence(runtime),
    );
  } catch (error) {
    failure = error;
    if (report.preflight.result === 'not_run') report.preflight.result = 'fail';
    if (report[stage] && report[stage].result === 'not_run') report[stage].result = 'fail';
  }

  try {
    stage = 'cleanup';
    // Switch to the separately reserved cleanup window before any browser
    // teardown or compensating write. Non-cleanup requests can never consume
    // this final 30-minute budget.
    runtime.cleanupStarted = true;
    const resourceFailures = await closeBrowsers(runtime);
    if (resourceFailures.length) {
      failure = failure || new DrillError('cleanup',
        'one or more browser resources missed their bounded close',
        undefined, 'browser_close_timeout');
    }
    cleanupResult = await cleanup(runtime);
    report.cleanup_ok = cleanupResult.ok;
    report.deleted_member_count = cleanupResult.deletedMembers;
    if (!cleanupResult.ok) {
      failure = failure || cleanupResult.error
        || new DrillError('cleanup', 'one or more TEST cleanup targets remain incomplete',
          undefined, 'cleanup_incomplete');
    }
  } catch (error) {
    failure = failure || error;
  }

  try {
    const flagsBefore = runtime.flagsBefore;
    const flagsAfter = runtime.client
      ? await runtimeFlags(runtime, 'flag_invariant')
      : null;
    report.flags_unchanged = Boolean(flagsBefore && flagsAfter
      && stableJson(flagsBefore) === stableJson(flagsAfter));
    if (runtime.flagsBefore && !report.flags_unchanged) {
      failure = failure || new DrillError('flag_invariant',
        'runtime flags changed during the TEST drill', undefined, 'flags_changed');
    }
  } catch (error) {
    failure = failure || error;
  }

  if (!failure && report.cleanup_ok && report.flags_unchanged) {
    try {
      stage = 'read_rebaseline';
      report.read_rebaseline = runReadRebaseline(runtime);
    } catch (error) {
      failure = error;
      report.read_rebaseline.result = 'fail';
    }
  }

  const code = failure instanceof DrillError && ERROR_CODES.has(failure.stage)
    ? failure.stage
    : failure
      ? (ERROR_CODES.has(stage) ? stage : 'preflight')
      : 'none';
  report.error_code = code;
  // Which GATE refused, as an allowlisted snake_case enum. Paired with the
  // stage this is enough to diagnose a failed run without runner access, and it
  // is structurally incapable of carrying a message, id or slug.
  report.failure_code = failure
    ? (failure instanceof DrillError && FAILURE_CODES.has(failure.code)
      ? failure.code
      : 'unclassified_failure')
    : 'none';
  report.ok = !failure
    && report.cleanup_ok
    && report.flags_unchanged
    && report.read_rebaseline.passed === true;

  if (failure && config.privateLogPath) {
    try {
      writePrivateFailure(failure, code, config.privateLogPath, config.repoRoot);
    } catch (_) {
      report.ok = false;
      report.error_code = 'report';
    }
  }
  let publicReport;
  try {
    publicReport = sanitizePublicReport(report);
  } catch (error) {
    if (config.privateLogPath) {
      try { writePrivateFailure(error, 'report', config.privateLogPath, config.repoRoot); } catch (_) {}
    }
    publicReport = sanitizePublicReport({
      ...emptyReport(),
      error_code: 'report',
      failure_code: 'report_sanitize_failed',
    });
  }
  if (config.reportPath) {
    const output = path.resolve(config.reportPath);
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, JSON.stringify(publicReport, null, 2));
  }
  // Failure-ONLY companion. Written just when the run failed, so the workflow
  // has something to upload and echo without parsing the aggregate, and so a
  // successful run leaves no failure artifact to misread. Same two enums the
  // aggregate carries; the workflow runs the same schema validator over it.
  if (!publicReport.ok && config.failureReportPath) {
    try {
      const failureOutput = path.resolve(config.failureReportPath);
      fs.mkdirSync(path.dirname(failureOutput), { recursive: true });
      fs.writeFileSync(failureOutput, JSON.stringify({
        schema_version: 1,
        stage: publicReport.error_code,
        failure_code: publicReport.failure_code,
      }, null, 2));
    } catch (_) { /* never let reporting mask the original failure */ }
  }
  process.stdout.write(`${JSON.stringify(publicReport)}\n`);
  if (!publicReport.ok) process.exitCode = 1;
  return publicReport;
}

