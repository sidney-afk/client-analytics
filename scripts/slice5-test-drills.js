function memberReferenceIds(value, found = [], seen = new WeakSet()) {
  if (typeof value === 'string') {
    const encoded = clean(value);
    if (/^[{[]/.test(encoded)) {
      try {
        const parsed = JSON.parse(encoded);
        memberReferenceIds(parsed, found, seen);
      } catch (_) {}
    }
    return found;
  }
  if (Array.isArray(value)) {
    if (seen.has(value)) return found;
    seen.add(value);
    value.forEach(item => memberReferenceIds(item, found, seen));
    return found;
  }
  if (!value || typeof value !== 'object') return found;
  if (seen.has(value)) return found;
  seen.add(value);
  for (const [key, child] of Object.entries(value)) {
    if (/^(?:assignee_id|member_id|.*_member_id)$/.test(key)) {
      const id = clean(child);
      if (id) found.push(id);
    } else {
      memberReferenceIds(child, found, seen);
    }
  }
  return found;
}

function postgrestMemberReferenceIds(resource) {
  const query = clean(resource).split('?').slice(1).join('?');
  if (!query) return [];
  const found = [];
  for (const [key, rawValue] of new URLSearchParams(query)) {
    if (!/^(?:assignee_id|member_id|.*_member_id)$/.test(key)) continue;
    let value = clean(rawValue);
    value = value.replace(/^(?:eq|neq|gt|gte|lt|lte|like|ilike)\./, '');
    if (/^in\.\(.*\)$/.test(value)) value = value.slice(4, -1);
    for (const candidate of value.split(',').map(clean).filter(Boolean)) {
      if (!['null', 'is.null'].includes(lower(candidate))) found.push(candidate);
    }
  }
  return [...new Set(found)];
}

function assertNoLogicalMutationFilters(resource, stage) {
  const query = clean(resource).split('?').slice(1).join('?');
  if (!query) return true;
  for (const [key] of new URLSearchParams(query)) {
    assert(!/(?:^|\.)(?:or|and|not)(?:\.|$)/.test(lower(key)), stage,
      'logical PostgREST filters are forbidden on drill mutation resources',
      undefined, 'rest_write_filter_forbidden');
  }
  return true;
}

