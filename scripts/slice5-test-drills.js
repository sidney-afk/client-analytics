async function restWrite(runtime, resource, options) {
  options = options || {};
  const rows = Array.isArray(options.body) ? options.body : [options.body];
  if (options.memberInsert) {
    await assertSyntheticMemberInsertAllowed(runtime, rows);
    // Reserve inside the adapter after the absence/marker proof and before the
    // fetch. A committed response loss is therefore still recoverable.
    rows.forEach(row => runtime.createdMemberIds.add(clean(row.id)));
  }
  for (const row of rows) {
    const assigneeId = clean(row && row.assignee_id);
    if (assigneeId) await assertSyntheticMemberMutationAllowed(runtime, assigneeId, options.stage);
  }
  if (options.memberId) {
    await assertSyntheticMemberMutationAllowed(runtime, options.memberId, options.stage);
  }
  if (options.deliverableId) await assertRunOwnedDeliverable(runtime, options.deliverableId, options.stage);
  if (options.batchId) await assertRunOwnedBatch(runtime, options.batchId, options.stage);
  await assertActiveTestWriteTarget(options.targetClientSlug, runtime);
  const response = await runtime.fetch(`${runtime.config.supabaseUrl}/rest/v1/${resource}`, {
    method: options.method || 'POST',
    headers: {
      apikey: runtime.config.serviceKey,
      Authorization: `Bearer ${runtime.config.serviceKey}`,
      Accept: 'application/json',
      'Content-Type': 'application/json',
      Prefer: options.prefer || 'return=representation',
    },
    body: JSON.stringify(options.body),
  });
  const body = await responseBody(response);
  if (!response.ok) {
    fail(options.stage || 'cleanup', 'guarded Supabase write failed', {
      resource: resource.split('?')[0],
      status: response.status,
      body,
    });
  }
  return body;
}

async function edgeWrite(runtime, functionName, body, options) {
  options = options || {};
  if (options.deliverableId) await assertRunOwnedDeliverable(runtime, options.deliverableId, options.stage);
  if (options.batchId) await assertRunOwnedBatch(runtime, options.batchId, options.stage);
  await assertActiveTestWriteTarget(options.targetClientSlug, runtime);
  const response = await runtime.fetch(
    `${runtime.config.supabaseUrl}/functions/v1/${encodeURIComponent(functionName)}`,
    {
      method: 'POST',
      headers: {
        apikey: runtime.config.serviceKey,
        Authorization: `Bearer ${runtime.config.serviceKey}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(body),
    },
  );
  const parsed = await responseBody(response);
  if (!response.ok || !parsed || parsed.ok !== true) {
    fail(options.stage || 'cleanup', 'guarded Edge write failed', {
      functionName,
      status: response.status,
      body: parsed,
    });
  }
  return parsed;
}

async function gatewayWrite(runtime, body, options) {
  options = options || {};
  if (options.trackDedup === true && body.id && body.operation && body.request_id) {
    runtime.createdDedups.add(`write-ui:${lower(body.operation)}:${lower(body.entity || 'deliverable')}:`
      + `${clean(body.id)}:${clean(body.request_id)}`);
  }
  if (body.id) await assertRunOwnedDeliverable(runtime, body.id, options.stage);
  const assigneeId = clean(body.assignee_id == null ? parseJson(body.patch).assignee_id : body.assignee_id);
  if (assigneeId) await assertSyntheticMemberMutationAllowed(runtime, assigneeId, options.stage);
  if (options.actorMemberId) {
    await assertSyntheticMemberMutationAllowed(runtime, options.actorMemberId, options.stage);
  }
  await assertActiveTestWriteTarget(options.targetClientSlug, runtime);
  const staff = options.staff || null;
  const headers = staff ? {
    apikey: runtime.config.publicAnonKey,
    Authorization: `Bearer ${runtime.config.publicAnonKey}`,
    'Content-Type': 'application/json',
    'X-Syncview-Key': staff.key,
    'X-Syncview-Actor': staff.name,
    'X-Syncview-Role': staff.role,
  } : {
    apikey: runtime.config.serviceKey,
    Authorization: `Bearer ${runtime.config.serviceKey}`,
    'Content-Type': 'application/json',
  };
  const response = await runtime.fetch(
    `${runtime.config.supabaseUrl}/functions/v1/production-write`,
    { method: 'POST', headers, body: JSON.stringify(body) },
  );
  return { status: response.status, body: await responseBody(response) };
}

// Exact browser verifier courier. Values stay in Node request headers; they are
// never injected through addInitScript, evaluate, or localStorage. The route
// firewall separately admits only the exact TEST drill couriers named below.
async function guardedBrowserVerifier(runtime, request, roleKey, options) {
  options = options || {};
  const parsed = new URL(request.url());
  assert(request.method() === 'POST'
      && parsed.origin === runtime.config.supabaseUrl
      && parsed.pathname === '/functions/v1/key-verify',
  options.stage || 'f37_identity', 'browser POST is not the exact verifier endpoint');
  await assertActiveTestWriteTarget(options.targetClientSlug, runtime);
  const headers = {
    ...request.headers(),
    'x-syncview-key': roleKey,
  };
  const response = await runtime.fetch(request.url(), {
    method: 'POST',
    headers,
    body: request.postData() || undefined,
  });
  const body = Buffer.from(await response.arrayBuffer());
  return {
    status: response.status,
    headers: Object.fromEntries(response.headers.entries()),
    body,
  };
}

async function linearRead(runtime, query, variables = {}, stage = 'preflight') {
  const response = await runtime.fetch(LINEAR_URL, {
    method: 'POST',
    headers: {
      Authorization: runtime.config.linearKey,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({ query, variables }),
  });
  const body = await responseBody(response);
  if (!response.ok || !body || body.errors) {
    fail(stage, 'Linear read failed', { status: response.status, errors: body && body.errors });
  }
  return body.data;
}

async function poll(stage, label, fn, timeoutMs = 60_000, intervalMs = 750) {
  const deadline = Date.now() + timeoutMs;
  let last = null;
  while (Date.now() < deadline) {
    last = await fn();
    if (last) return last;
    await sleep(intervalMs);
  }
  fail(stage, `${label} timed out`, { last });
}

function projectIdsForTeam(value, wantedTeam) {
  const wanted = lower(wantedTeam);
  const found = new Set();
  const idsFrom = entry => {
    if (typeof entry === 'string' && clean(entry)) return [clean(entry)];
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return [];
    return ['id', 'project_id', 'linear_project_id'].map(key => clean(entry[key])).filter(Boolean);
  };
  const addExplicit = entry => {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) return;
    const team = lower(entry.team || entry.team_key || entry.key || entry.kind);
    if (team === wanted) idsFrom(entry).forEach(id => found.add(id));
  };
  if (Array.isArray(value)) value.forEach(addExplicit);
  else if (value && typeof value === 'object') {
    for (const [key, entry] of Object.entries(value)) {
      if (lower(key) === wanted) idsFrom(entry).forEach(id => found.add(id));
    }
    addExplicit(value);
    if (Array.isArray(value.projects)) value.projects.forEach(addExplicit);
  }
  return [...found].sort();
}

