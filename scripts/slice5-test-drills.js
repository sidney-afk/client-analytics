async function assertContextsConverge(runtime, pages, predicate, label) {
  const started = Date.now();
  while (Date.now() - started <= MATRIX_TICK_MS) {
    const remaining = Math.max(1, MATRIX_TICK_MS - (Date.now() - started));
    const rows = await Promise.all(pages.map((page, index) => pageEvaluate(
      runtime,
      'f95_convergence',
      `${label} convergence context ${index + 1}`,
      page,
      id => {
        const row = (_prodState.deliverables || [])
          .find(item => String(item.id || '') === String(id));
        return row || null;
      },
      runtime.fixture.deliverableId,
      remaining,
    )));
    const elapsed = Date.now() - started;
    if (rows.every((row, index) => predicate(row, index)) && elapsed <= MATRIX_TICK_MS) {
      return elapsed;
    }
    if (elapsed >= MATRIX_TICK_MS) break;
    await sleep(250);
  }
  fail('f95_convergence', `${label} did not converge within one foreground tick`,
    undefined, 'f95_context_not_converged');
}

