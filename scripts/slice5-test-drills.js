function expectedCreativeAcceptedSet(policy, currentStatus, ownership) {
  if (ownership !== 'own') return [];
  return [...(policy.CREATIVE_STATUS_TRANSITIONS[lower(currentStatus)] || [])];
}

function expectedRoleAcceptance(policy, role, currentStatus, nextStatus, ownership) {
  if (role === 'admin' || role === 'smm') return true;
  return expectedCreativeAcceptedSet(policy, currentStatus, ownership).includes(nextStatus);
}

function classifyMatrixAttempt(status, body) {
  const code = clean(body && body.error);
  if (status === 403 && code === 'operation_forbidden') return 'forbidden';
  // Intentional policy oracle: staffOperationAllowed runs before authorityLane.
  // This exact 409 proves the request passed the role/current/next/ownership
  // decision but was fenced because Video remains Linear-authoritative.
  if (status === 409 && code === 'team_is_linear_authoritative') return 'authority_fenced';
  return 'unexpected';
}

