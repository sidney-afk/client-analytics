function writePrivateFailure(error, stage, outputPath, repoRoot = path.resolve(__dirname, '..')) {
  if (!error || !outputPath) return false;
  const resolved = path.resolve(outputPath);
  const relative = path.relative(path.resolve(repoRoot), resolved);
  if (!relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error('SLICE5_TEST_DRILLS_PRIVATE_LOG must resolve outside the public repository');
  }
  fs.mkdirSync(path.dirname(resolved), { recursive: true });
  fs.writeFileSync(resolved, JSON.stringify({
    stage: clean(stage) || 'preflight',
    message: clean(error.message),
    detail: error.detail || null,
    stack: clean(error.stack),
  }, null, 2));
  return true;
}

