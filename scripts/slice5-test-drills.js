    assert(attempts === expectedAttempts, 'f136_matrix', 'matrix is incomplete');
    assert(listState.matrixWrites + directState.matrixWrites === attempts
        && listState.matrixWrites > 0
        && directState.matrixWrites > 0
        && !listState.routeError
        && !directState.routeError,
    'f136_matrix', 'matrix did not traverse both guarded browser couriers');

