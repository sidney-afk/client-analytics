async function ensureDedupTerminal(runtime, dedup) {
  let rows = await restRead(runtime,
    `mirror_outbox?select=id,dedup_key,status,entity,entity_id,client_slug,test_only`
      + `&dedup_key=eq.${encodeURIComponent(dedup)}&limit=2`,
    { stage: 'cleanup' });
  // A reserved request whose fetch failed before commit has no residue.
  if (Array.isArray(rows) && rows.length === 0) return true;
  assert(Array.isArray(rows) && rows.length === 1
      && clean(rows[0].client_slug) === runtime.client.slug
      && rows[0].test_only === true,
  'cleanup', 'tracked TEST outbox intent is missing, ambiguous, or out of scope');
  const terminal = new Set(['written', 'skipped', 'stale']);
  if (!terminal.has(lower(rows[0].status))) {
    await drainTestOutbox(runtime, dedup, 'cleanup');
  }
  rows = await poll('cleanup', 'tracked outbox terminal receipt', async () => {
    const current = await restRead(runtime,
      `mirror_outbox?select=id,dedup_key,status,entity,entity_id,client_slug,test_only`
        + `&dedup_key=eq.${encodeURIComponent(dedup)}&limit=2`,
      { stage: 'cleanup' });
    return Array.isArray(current) && current.length === 1
        && terminal.has(lower(current[0].status))
      ? current
      : null;
  });
  return rows.length === 1;
}

async function cleanupRunComments(runtime) {
  const deliverableIds = [...runtime.createdDeliverableIds];
  if (!deliverableIds.length) return 0;
  const rows = await restRead(runtime,
    `production_comments?select=*&deliverable_id=in.(${deliverableIds
      .map(encodeURIComponent).join(',')})&order=created_at.asc`,
    { stage: 'cleanup' });
  const owned = (rows || []).filter(row => markerPresent(row.body, runtime));
  for (const id of runtime.createdCommentIds) {
    assert(owned.some(row => clean(row.id) === clean(id)), 'cleanup',
      'committed drill comment is missing from cleanup recovery');
  }
  for (const row of owned) {
    if (clean(row.deleted_at)) continue;
    const request = requestId(runtime, 'cleanup-comment-delete');
    const dedup = `write-ui:comment:deliverable:${clean(row.deliverable_id)}:${request}`;
    const response = await gatewayWrite(runtime, gatewayServiceBody(runtime, {
      operation: 'comment',
      surface: 'production',
      entity: 'deliverable',
      id: clean(row.deliverable_id),
      request_id: request,
      comment: {
        action: 'delete',
        id: clean(row.id),
        expected_version: Number(row.version),
        expected_updated_at: clean(row.updated_at),
      },
    }), {
      targetClientSlug: runtime.client.slug,
      stage: 'cleanup',
      trackDedup: true,
    });
    assert(response.status >= 200 && response.status < 300
        && response.body && response.body.ok === true,
    'cleanup', 'drill comment tombstone did not commit');
    await ensureDedupTerminal(runtime, dedup);
  }
  const deleted = await restRead(runtime,
    `production_comments?select=id,body,deleted_at&deliverable_id=in.(${deliverableIds
      .map(encodeURIComponent).join(',')})&order=created_at.asc`,
    { stage: 'cleanup' });
  assert((deleted || []).filter(row => markerPresent(row.body, runtime))
    .every(row => !!clean(row.deleted_at)),
  'cleanup', 'drill comment cleanup is incomplete');
  return owned.length;
}

async function cleanup(runtime) {
  // Cleanup reads deliverable_events and mirror_outbox residue before deleting
  // any run-owned team_members; audit events remain durable but can reference
  // only the generated batch/deliverable allowlists.
  const deliverableIds = [...runtime.createdDeliverableIds];
  const batchIds = [...runtime.createdBatchIds];
  for (const id of deliverableIds) {
    const events = await restRead(runtime,
      `deliverable_events?select=id,deliverable_id,batch_id&deliverable_id=eq.${encodeURIComponent(id)}`,
      { stage: 'cleanup' });
    assert(Array.isArray(events) && events.every(event =>
      clean(event.deliverable_id) === id
      && (!clean(event.batch_id) || runtime.createdBatchIds.has(clean(event.batch_id)))),
    'cleanup', 'deliverable event residue escaped the run-owned TEST rows');
  }

  // Recover every pre-cleanup request before creating archive intents. Set
  // insertion order preserves the batch-create -> deliverable-create dependency,
  // so response loss cannot strand a provider issue that appears after cleanup.
  for (const dedup of [...runtime.createdDedups]) {
    await ensureDedupTerminal(runtime, dedup);
  }

  await cleanupRunComments(runtime);
  let archivedRows = 0;
  let recoveredRows = 0;
  const providerIssueIds = new Set();
  for (const id of deliverableIds) {
    let row = await optionalRunOwnedDeliverable(runtime, id);
    if (!row) continue;
    recoveredRows += 1;
    if (clean(row.assignee_id)) {
      row = await servicePatchDeliverable(runtime, id, { assignee_id: null }, 'cleanup');
    }
    const issueId = await providerIssueIdFor(runtime, 'deliverable', id, row);
    const dedup = requestId(runtime, 'cleanup-deliverable-archive');
    await ledgerWrite(runtime, 'deliverable', {
      id,
      operation: 'archive',
      dedup,
      patch: {},
      linearPayload: issueId ? { linear_issue_id: issueId } : {},
    }, 'cleanup');
    await drainTestOutbox(runtime, dedup, 'cleanup');
    row = await poll('cleanup', 'native deliverable archive marker', async () => {
      const current = await optionalRunOwnedDeliverable(runtime, id);
      return current && !!parseJson(current.linear_raw).archived ? current : null;
    });
    if (issueId) providerIssueIds.add(issueId);
    archivedRows += 1;
  }
  for (const id of batchIds) {
    let row = await optionalRunOwnedBatch(runtime, id);
    if (!row) continue;
    recoveredRows += 1;
    const issueId = await providerIssueIdFor(runtime, 'batch', id, row);
    const dedup = requestId(runtime, 'cleanup-batch-archive');
    await ledgerWrite(runtime, 'batch', {
      id,
      operation: 'archive',
      dedup,
      patch: { status: 'archived' },
      linearPayload: issueId ? { linear_issue_id: issueId } : {},
    }, 'cleanup');
    await drainTestOutbox(runtime, dedup, 'cleanup');
    row = await poll('cleanup', 'native batch archive marker', async () => {
      const current = await optionalRunOwnedBatch(runtime, id);
      return current && lower(current.status) === 'archived' ? current : null;
    });
    if (issueId) providerIssueIds.add(issueId);
    archivedRows += 1;
  }
  for (const issueId of providerIssueIds) {
    await poll('cleanup', 'Linear TEST issue archive', async () => {
      const issue = await linearIssueSnapshot(runtime, issueId);
      return clean(issue.archivedAt) ? issue : null;
    });
  }

  for (const dedup of runtime.createdDedups) {
    await ensureDedupTerminal(runtime, dedup);
  }
  for (const id of [...deliverableIds, ...batchIds]) {
    const outbox = await restRead(runtime,
      `mirror_outbox?select=id,status,dedup_key,client_slug,test_only`
        + `&entity_id=eq.${encodeURIComponent(id)}`
        + `&client_slug=eq.${encodeURIComponent(runtime.client.slug)}&test_only=eq.true`,
      { stage: 'cleanup' });
    assert((outbox || []).every(row => ['written', 'skipped', 'stale'].includes(lower(row.status))),
      'cleanup', 'run-owned TEST outbox residue is not terminal');
  }

  const memberIds = [...runtime.createdMemberIds];
  if (memberIds.length) {
    const refs = await restRead(runtime,
      `deliverables?select=id,client_slug,assignee_id&assignee_id=in.(${memberIds.map(encodeURIComponent).join(',')})`);
    assert(Array.isArray(refs) && refs.length === 0, 'cleanup',
      'synthetic members remain assigned to a deliverable', { refs });

    const actorNames = [...new Set(Object.values(runtime.members)
      .map(member => clean(member.name)).filter(Boolean))];
    assert(actorNames.every(name => markerPresent(name, runtime)), 'cleanup',
      'durable auth-event actor is not drill-marker-owned');
    // key-verify rows are durable security audit evidence, just like
    // deliverable_events. The drill deliberately retains marker-owned rows.
  }

  let deletedMembers = 0;
  for (const id of memberIds) {
    const existing = await restRead(runtime,
      `team_members?select=id,name,email&id=eq.${encodeURIComponent(id)}&limit=2`,
      { stage: 'cleanup' });
    // A reserved insert whose request failed before commit is already clean.
    if (Array.isArray(existing) && existing.length === 0) continue;
    assert(Array.isArray(existing) && existing.length === 1
        && (markerPresent(existing[0].name, runtime)
          || markerPresent(existing[0].email, runtime)),
    'cleanup', 'synthetic member recovery target is not marker-owned');
    await restWrite(runtime, `team_members?id=eq.${encodeURIComponent(id)}`, {
      method: 'DELETE',
      body: null,
      memberId: id,
      targetClientSlug: runtime.client.slug,
      stage: 'cleanup',
    });
    deletedMembers += 1;
  }
  const survivors = memberIds.length
    ? await restRead(runtime,
      `team_members?select=id&id=in.(${memberIds.map(encodeURIComponent).join(',')})`)
    : [];
  assert(Array.isArray(survivors) && survivors.length === 0, 'cleanup',
    'synthetic member cleanup is incomplete');
  return {
    ok: survivors.length === 0
      && archivedRows === recoveredRows,
    deletedMembers,
  };
}

function runReadRebaseline(runtime) {
  const probe = path.join(runtime.config.repoRoot, 'qa/probes/prod_read_path_timing.js');
  assert(fs.existsSync(probe), 'read_rebaseline', 'read-only timing probe is missing');
  const childEnv = {
    PATH: process.env.PATH,
    Path: process.env.Path,
    SystemRoot: process.env.SystemRoot,
    WINDIR: process.env.WINDIR,
    TEMP: process.env.TEMP,
    TMP: process.env.TMP,
    HOME: process.env.HOME,
    USERPROFILE: process.env.USERPROFILE,
    SUPABASE_URL: runtime.config.supabaseUrl,
    SUPABASE_ANON_KEY: runtime.config.publicAnonKey,
    REPS: '3',
  };
  Object.keys(childEnv).forEach(key => {
    if (!clean(childEnv[key])) delete childEnv[key];
  });
  const result = spawnSync(process.execPath, [probe, 'delta'], {
    cwd: runtime.config.repoRoot,
    env: childEnv,
    encoding: 'utf8',
    timeout: 5 * 60 * 1000,
  });
  const raw = `${result.stdout || ''}\n${result.stderr || ''}`;
  const failedMarker = /\b(?:FAILED|ABORTED)\s*=/i.test(raw)
    || /\b(?:FAILED|ABORTED)\b/i.test(raw);
  assert(result.status === 0 && !result.error && !failedMarker, 'read_rebaseline',
    'read-only timing rebaseline did not pass', {
      status: result.status,
      signal: result.signal,
      error: result.error && result.error.message,
      output: raw,
    });
  const medianMatches = [...raw.matchAll(/\bwall_med=(\d+(?:\.\d+)?)ms\b/gi)]
    .map(match => Number(match[1]));
  assert(medianMatches.length === 3
      && medianMatches.every(value => Number.isFinite(value) && value <= MATRIX_TICK_MS),
  'read_rebaseline', 'timing probe did not report bounded wall medians', { output: raw });
  return { result: 'pass', mode_count: 1, passed: true };
}

