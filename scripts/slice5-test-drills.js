async function responseBody(response) {
  const text = await response.text();
  if (!text) return null;
  try { return JSON.parse(text); } catch (_) { return { _unparsed: true }; }
}

async function restRead(runtime, resource, options = {}) {
  const response = await runtime.fetch(`${runtime.config.supabaseUrl}/rest/v1/${resource}`, {
    method: options.method || 'GET',
    headers: {
      apikey: runtime.config.serviceKey,
      Authorization: `Bearer ${runtime.config.serviceKey}`,
      Accept: 'application/json',
      ...(options.headers || {}),
    },
  });
  const body = await responseBody(response);
  if (!response.ok) {
    fail(options.stage || 'preflight', 'Supabase read failed', {
      resource: resource.split('?')[0],
      status: response.status,
      body,
    });
  }
  return body;
}

