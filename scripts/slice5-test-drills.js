async function closeContext(runtime, context) {
  if (!context) return true;
  try {
    await boundedOperation(
      runtime, 'cleanup', 'browser context close',
      () => context.close(), RESOURCE_CLOSE_TIMEOUT_MS,
    );
    runtime.contexts.delete(context);
    return true;
  } catch (error) {
    // Keep an unsuccessfully closed context registered so the central browser-
    // server kill can neutralize and account for it.
    throw error;
  }
}

async function closeStaticServer(runtime, server) {
  if (!server) return true;
  try {
    await boundedOperation(
      runtime,
      'cleanup',
      'local TEST server close',
      () => neutralizeStaticServer(server),
      RESOURCE_CLOSE_TIMEOUT_MS,
    );
    runtime.servers.delete(server);
    return true;
  } catch (error) {
    // neutralizeStaticServer synchronously closes listeners/connections and
    // unrefs the handle before its completion promise is awaited.
    runtime.servers.delete(server);
    throw error;
  }
}

