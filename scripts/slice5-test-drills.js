async function cleanupSyntheticMembers(runtime, deliverableIds) {
  const errors = [];
  const memberIds = [...runtime.createdMemberIds];
  let deletedMembers = 0;
  let survivors = memberIds;
  let ambiguitySettled = runtime.ambiguousMemberIds.size === 0;
  const capture = error => errors.push(error instanceof Error
    ? error
    : new DrillError('cleanup', 'synthetic member cleanup failed',
      undefined, 'cleanup_member_incomplete'));

  // Retry assignment clearing independently of the archive phase. This finally-
  // owned pass still runs when a prior audit, provider, or outbox read failed.
  for (const id of deliverableIds) {
    try {
      const row = await optionalRunOwnedDeliverable(runtime, id);
      if (row && runtime.createdMemberIds.has(clean(row.assignee_id))) {
        await servicePatchDeliverable(runtime, id, { assignee_id: null }, 'cleanup');
      }
    } catch (error) {
      capture(error);
    }
  }

  if (memberIds.length) {
    try {
      const refs = await restRead(runtime,
        `deliverables?select=id,client_slug,assignee_id`
          + `&assignee_id=in.(${memberIds.map(encodeURIComponent).join(',')})`,
        { stage: 'cleanup' });
      assert(Array.isArray(refs) && refs.length === 0, 'cleanup',
        'synthetic members remain assigned to a deliverable', { refs },
        'cleanup_member_still_assigned');
    } catch (error) {
      capture(error);
    }

    try {
      const actorNames = [...new Set(Object.values(runtime.members)
        .map(member => clean(member.name)).filter(Boolean))];
      assert(actorNames.every(name => markerPresent(name, runtime)), 'cleanup',
        'durable auth-event actor is not drill-marker-owned',
        undefined, 'cleanup_auth_event_foreign');
      // key-verify rows are durable security audit evidence, just like
      // deliverable_events. The drill deliberately retains marker-owned rows.
    } catch (error) {
      capture(error);
    }
  }

  if (runtime.ambiguousMemberIds.size > 0) {
    try {
      const settleUntil = Number(runtime.ambiguousMemberWriteAt)
        + AMBIGUOUS_WRITE_SETTLE_MS;
      const settleMs = Math.max(0, settleUntil - Date.now());
      assert(Date.now() + settleMs < runtime.processDeadlineAt,
        'cleanup', 'insufficient cleanup budget for ambiguous member-write settlement',
        undefined, 'cleanup_budget_exhausted');
      if (settleMs > 0) await sleep(settleMs);
      ambiguitySettled = true;
    } catch (error) {
      capture(error);
    }
  }

  for (const id of memberIds) {
    try {
      const existing = await restRead(runtime,
        `team_members?select=id,name,email&id=eq.${encodeURIComponent(id)}&limit=2`,
        { stage: 'cleanup' });
      // A reserved insert whose request failed before commit is already clean.
      if (Array.isArray(existing) && existing.length === 0) continue;
      assert(Array.isArray(existing) && existing.length === 1
          && (markerPresent(existing[0].name, runtime)
            || markerPresent(existing[0].email, runtime)),
      'cleanup', 'synthetic member recovery target is not marker-owned',
      undefined, 'cleanup_recovery_target_foreign');
      await restWrite(runtime, `team_members?id=eq.${encodeURIComponent(id)}`, {
        method: 'DELETE',
        body: null,
        memberId: id,
        targetClientSlug: runtime.client.slug,
        stage: 'cleanup',
      });
      deletedMembers += 1;
    } catch (error) {
      capture(error);
    }
  }

  try {
    survivors = memberIds.length
      ? await restRead(runtime,
        `team_members?select=id&id=in.(${memberIds.map(encodeURIComponent).join(',')})`,
        { stage: 'cleanup' })
      : [];
    assert(Array.isArray(survivors) && survivors.length === 0, 'cleanup',
      'synthetic member cleanup is incomplete', undefined, 'cleanup_member_incomplete');
  } catch (error) {
    capture(error);
  }
  return {
    ok: errors.length === 0
      && ambiguitySettled
      && Array.isArray(survivors)
      && survivors.length === 0,
    deletedMembers,
    errors,
  };
}

async function cleanup(runtime) {
  // Every recovery target is attempted independently. A failed provider/read
  // proof cannot skip the remaining outbox, row, or disposable-member work.
  const deliverableIds = [...runtime.createdDeliverableIds];
  const batchIds = [...runtime.createdBatchIds];
  const errors = [];
  const capture = error => errors.push(error instanceof Error
    ? error
    : new DrillError('cleanup', 'TEST cleanup target failed',
      undefined, 'cleanup_incomplete'));
  let archivedRows = 0;
  let recoveredRows = 0;
  const providerIssueIds = new Map();

  for (const id of deliverableIds) {
    try {
      const events = await restRead(runtime,
        `deliverable_events?select=id,deliverable_id,batch_id`
          + `&deliverable_id=eq.${encodeURIComponent(id)}`,
        { stage: 'cleanup' });
      assert(Array.isArray(events) && events.every(event =>
        clean(event.deliverable_id) === id
        && (!clean(event.batch_id) || runtime.createdBatchIds.has(clean(event.batch_id)))),
      'cleanup', 'deliverable event residue escaped the run-owned TEST rows',
      undefined, 'cleanup_event_residue_foreign');
    } catch (error) {
      capture(error);
    }
  }

  // Recover pre-cleanup requests before creating archive intents. Insertion
  // order preserves the batch-create -> deliverable-create dependency.
  for (const dedup of [...runtime.createdDedups]) {
    try {
      await ensureDedupTerminal(runtime, dedup);
    } catch (error) {
      capture(error);
    }
  }

  try {
    await cleanupRunComments(runtime);
  } catch (error) {
    capture(error);
  }

  for (const id of deliverableIds) {
    try {
      let row = await optionalRunOwnedDeliverable(runtime, id);
      if (!row) continue;
      recoveredRows += 1;
      if (clean(row.assignee_id)) {
        row = await servicePatchDeliverable(runtime, id, { assignee_id: null }, 'cleanup');
      }
      const issueId = await providerIssueIdFor(runtime, 'deliverable', id, row);
      if (issueId) providerIssueIds.set(issueId, 'deliverable');
      const dedup = requestId(runtime, 'cleanup-deliverable-archive');
      await ledgerWrite(runtime, 'deliverable', {
        id,
        operation: 'archive',
        dedup,
        patch: {},
        linearPayload: issueId ? { linear_issue_id: issueId } : {},
      }, 'cleanup');
      await drainTestOutbox(runtime, dedup, 'cleanup', 'terminal');
      await poll(runtime, 'cleanup', 'native deliverable archive marker',
        'cleanup_deliverable_archive_timeout', async () => {
        const current = await optionalRunOwnedDeliverable(runtime, id);
        return current && !!parseJson(current.linear_raw).archived ? current : null;
      });
      archivedRows += 1;
    } catch (error) {
      capture(error);
    }
  }

  for (const id of batchIds) {
    try {
      const row = await optionalRunOwnedBatch(runtime, id);
      if (!row) continue;
      recoveredRows += 1;
      const issueId = await providerIssueIdFor(runtime, 'batch', id, row);
      if (issueId) providerIssueIds.set(issueId, 'batch');
      const dedup = requestId(runtime, 'cleanup-batch-archive');
      await ledgerWrite(runtime, 'batch', {
        id,
        operation: 'archive',
        dedup,
        patch: { status: 'archived' },
        linearPayload: issueId ? { linear_issue_id: issueId } : {},
      }, 'cleanup');
      await drainTestOutbox(runtime, dedup, 'cleanup', 'terminal');
      await poll(runtime, 'cleanup', 'native batch archive marker',
        'cleanup_batch_archive_timeout', async () => {
        const current = await optionalRunOwnedBatch(runtime, id);
        return current && lower(current.status) === 'archived' ? current : null;
      });
      archivedRows += 1;
    } catch (error) {
      capture(error);
    }
  }

  for (const [issueId, kind] of providerIssueIds) {
    try {
      await poll(runtime, 'cleanup', 'Linear TEST issue archive',
        'cleanup_linear_archive_timeout', async () => {
        const issue = await linearIssueSnapshot(runtime, issueId, kind);
        return clean(issue.archivedAt) ? issue : null;
      });
    } catch (error) {
      capture(error);
    }
  }

  for (const dedup of runtime.createdDedups) {
    try {
      await ensureDedupTerminal(runtime, dedup);
    } catch (error) {
      capture(error);
    }
  }
  for (const id of [...deliverableIds, ...batchIds]) {
    try {
      const outbox = await restRead(runtime,
        `mirror_outbox?select=id,status,dedup_key,client_slug,test_only`
          + `&entity_id=eq.${encodeURIComponent(id)}`
          + `&client_slug=eq.${encodeURIComponent(runtime.client.slug)}&test_only=eq.true`,
        { stage: 'cleanup' });
      assert((outbox || []).every(row =>
        ['written', 'skipped', 'stale'].includes(lower(row.status))),
      'cleanup', 'run-owned TEST outbox residue is not terminal',
      undefined, 'cleanup_outbox_not_terminal');
    } catch (error) {
      capture(error);
    }
  }

  const memberCleanup = await cleanupSyntheticMembers(runtime, deliverableIds);
  memberCleanup.errors.forEach(capture);

  let rosterUnchanged = !Array.isArray(runtime.preExistingRoster);
  if (Array.isArray(runtime.preExistingRoster)) {
    try {
      await assertPreExistingRosterUnchanged(runtime, 'cleanup');
      rosterUnchanged = true;
    } catch (error) {
      capture(error);
    }
  }

  let runLedgerCleared = !runtime.runLedger;
  const cleanupProven = errors.length === 0
    && memberCleanup.ok
    && archivedRows === recoveredRows
    && rosterUnchanged;
  if (cleanupProven && runtime.runLedger) {
    try {
      runLedgerCleared = await clearDurableRunLedger(runtime);
    } catch (error) {
      capture(error);
    }
  }
  const ok = cleanupProven && errors.length === 0 && runLedgerCleared;
  return {
    ok,
    deletedMembers: memberCleanup.deletedMembers,
    error: ok ? null : errors[0]
      || new DrillError('cleanup', 'TEST cleanup proof is incomplete',
        undefined, 'cleanup_incomplete'),
  };
}

function runReadRebaseline(runtime) {
  const remaining = runtime.processDeadlineAt - Date.now();
  assert(remaining >= REBASELINE_BUDGET_MS + REPORT_RESERVE_MS,
    'read_rebaseline',
    'insufficient bounded process budget remains for rebaseline and reporting',
    undefined, 'rebaseline_budget_exhausted');
  const probe = path.join(runtime.config.repoRoot, 'qa/probes/prod_read_path_timing.js');
  assert(fs.existsSync(probe), 'read_rebaseline', 'read-only timing probe is missing',
    undefined, 'rebaseline_probe_missing');
  const childEnv = {
    PATH: process.env.PATH,
    Path: process.env.Path,
    SystemRoot: process.env.SystemRoot,
    WINDIR: process.env.WINDIR,
    TEMP: process.env.TEMP,
    TMP: process.env.TMP,
    HOME: process.env.HOME,
    USERPROFILE: process.env.USERPROFILE,
    SUPABASE_URL: runtime.config.supabaseUrl,
    SUPABASE_ANON_KEY: runtime.config.publicAnonKey,
    REPS: '3',
  };
  Object.keys(childEnv).forEach(key => {
    if (!clean(childEnv[key])) delete childEnv[key];
  });
  const result = spawnSync(process.execPath, [probe, 'delta'], {
    cwd: runtime.config.repoRoot,
    env: childEnv,
    encoding: 'utf8',
    timeout: REBASELINE_BUDGET_MS,
  });
  const raw = `${result.stdout || ''}\n${result.stderr || ''}`;
  const failedMarker = /\b(?:FAILED|ABORTED)\s*=/i.test(raw)
    || /\b(?:FAILED|ABORTED)\b/i.test(raw);
  assert(result.status === 0 && !result.error && !failedMarker, 'read_rebaseline',
    'read-only timing rebaseline did not pass', {
      status: result.status,
      signal: result.signal,
      error: result.error && result.error.message,
      output: raw,
    }, 'rebaseline_failed');
  const medianMatches = [...raw.matchAll(/\bwall_med=(\d+(?:\.\d+)?)ms\b/gi)]
    .map(match => Number(match[1]));
  assert(medianMatches.length === 3
      && medianMatches.every(value => Number.isFinite(value) && value <= MATRIX_TICK_MS),
  'read_rebaseline', 'timing probe did not report bounded wall medians', { output: raw },
  'rebaseline_medians_unbounded');
  return { result: 'pass', mode_count: 1, passed: true };
}

