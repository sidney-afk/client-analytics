'use strict';
const fs=require('fs'),assert=require('assert/strict'),api=require('../scripts/linear-exit-observed-full-install-plan'),j=require('../scripts/linear-exit-install-journal'),target=require('../scripts/linear-exit-observed-full-target');
assert(process.argv[2],'explicit private observed catalog path required');
const observed=JSON.parse(fs.readFileSync(process.argv[2]));
const result=api.build(observed.catalog),plan=JSON.parse(result.planBytes);
assert.equal(plan.sources.length,35+api.OWNERS.length);
assert.deepEqual(plan.sources.slice(-api.OWNERS.length).map(s=>s.id),api.OWNERS.map(s=>s.path));
assert.equal(new Set(plan.sources.map(s=>s.id)).size,plan.sources.length);
assert(result.decisions.some(d=>d.id==='2026-09-10-kasper-urgent-ping-ledger.sql'&&d.action==='PRESERVE_OBSERVED_PREEXISTING'));
assert(!plan.sources.some(s=>s.id==='2026-09-05-workload-native-membership.sql'));
const catalog={tables:Array.from({length:90},(_,i)=>({name:'synthetic_'+i}))},privateCatalog={synthetic:true};
const args={planBytes:result.planBytes,planSha256:result.planSha256,catalog,privateCatalog};
const bytes=Buffer.from(JSON.stringify(target.create(args))),check={...args,targetBytes:bytes,targetSha256:j.sha(bytes)};
assert.equal(target.compare(check).status,'MATCHED_SOURCE_DERIVED_TARGET');
assert.throws(()=>target.compare({...check,catalog:{...catalog,functions:['unexpected']}}));
assert.throws(()=>target.compare({...check,privateCatalog:{synthetic:false}}));
assert.throws(()=>target.compare({...check,targetSha256:'0'.repeat(64)}));
assert.throws(()=>api.build({...observed.catalog,tables:[]}));
console.log('OBSERVED_FULL_INSTALL_OFFLINE_OK 9');
