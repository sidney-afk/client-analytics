'use strict';
// thumbnail-titles, borrowed month tabs: a post whose own month has no filming plan tab borrows the
// next or previous month's tab, and is matched by video number. Numbering restarts every month, so
// the video may already have been used by an earlier post. Offline, invented data only: no network,
// no database, no model call. The rules under test:
//  1. a post whose video an earlier caption already used is NOT titled (borrowed_video_used);
//  2. a post whose video is clearly still unused IS titled;
//  3. anything unclear is needs_info (borrowed_unclear), never a guess;
//  4. every title from a borrowed tab says which plan it came from; own-month titles are unchanged;
//  5. only same-client captions inside the 90 day window, scheduled earlier, count as evidence.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const ROOT = path.resolve(__dirname, '..');
let checks = 0;
const ok = (c, m) => { assert.ok(c, m); checks++; };
const eq = (a, b, m) => { assert.deepEqual(a, b, m); checks++; };

(async () => {
  const L = await import(pathToFileURL(path.join(ROOT, 'supabase/functions/thumbnail-titles/logic.mjs')).href);
  const answer = (obj) => [{ type: 'text', text: JSON.stringify(obj) }];

  // --- Rule 4: the label -------------------------------------------------------------------------
  eq(L.titleLine('Calm Mornings'), 'Thumbnail title (generated by AI): Calm Mornings', 'own month: the label is exactly as before');
  eq(L.titleLine('Calm Mornings', ''), L.titleLine('Calm Mornings'), 'empty plan name = own month');
  eq(L.titleLine('Calm Mornings', 'August'), 'Thumbnail title (generated by AI, from the August plan): Calm Mornings', 'borrowed: names the plan');
  eq(L.borrowedPlanName('2026-09-28T10:00:00Z', 'previous_month'), 'August', 'a September post on the previous tab: August');
  eq(L.borrowedPlanName('2026-10-30T10:00:00Z', 'next_month'), 'November', 'an October post on the next tab: November');
  eq(L.borrowedPlanName('2026-01-05T10:00:00Z', 'previous_month'), 'December', 'January rolls back to December');
  eq(L.borrowedPlanName('2026-09-28T10:00:00Z', ''), '', 'no borrowing: no name');
  const plan = L.normalizedText('Video 1: Calm mornings for busy parents. Video 2: Why bread rises.');
  const own = L.resolveLine({ postName: 'Video 1' }, 'Calm Mornings', plan);
  eq([own.state, own.outcome, own.text], ['written', 'title', 'Thumbnail title (generated by AI): Calm Mornings'], 'resolveLine without a plan name is unchanged');
  const lent = L.resolveLine({ postName: 'Video 1' }, 'Calm Mornings', plan, 'August');
  eq([lent.state, lent.text], ['written', 'Thumbnail title (generated by AI, from the August plan): Calm Mornings'], 'resolveLine with a plan name labels the line');
  eq(L.resolveLine({ postName: 'Video 1' }, '', plan, 'August').outcome, 'no_match', 'no title is still no_match');
  eq(L.resolveLine({ postName: 'Video 1' }, 'Zebra Cheese Volcano', plan, 'August').outcome, 'not_grounded', 'grounding still applies on a borrowed tab');

  // --- The needs-info lines ------------------------------------------------------------------------
  const used = L.needsInfoLine('borrowed_video_used', { month: 'September 2026', plan: 'August', video: 5 });
  ok(used.startsWith('Needs info: ') && used.includes('September 2026') && used.includes('August plan') && used.includes('video 5') && /seems to be missing/.test(used), 'the used line names both months, the video and the missing plan');
  const unclear = L.needsInfoLine('borrowed_unclear', { month: 'September 2026', plan: 'August' });
  ok(unclear.startsWith('Needs info: ') && /could not be confirmed/.test(unclear) && /may be missing/.test(unclear), 'the unclear line says it could not be confirmed');
  ok(!/\{|\}/.test(used + unclear), 'no placeholder is left in either line');
  ok(L.needsInfoLine('no_month_tab', { month: 'October 2026' }).includes('no tab for October 2026'), 'the old no_month_tab line is unchanged');

  // --- Rule 5: which earlier captions count ---------------------------------------------------------
  const rows = [
    { id: 'a1', name: 'Video 1', caption: 'Caption about calm mornings', scheduled_date: '2026-08-04' },
    { id: 'a2', name: 'Video 2', caption: 'Caption about bread', scheduled_date: '2026-08-10' },
    { id: 'old', name: 'Old', caption: 'Too old', scheduled_date: '2026-05-01' },
    { id: 'later', name: 'Later', caption: 'Scheduled after the card', scheduled_date: '2026-10-20' },
    { id: 'blank', name: 'Blank', caption: '   ', scheduled_date: '2026-08-12' },
    { id: 'nodate', name: 'No date', caption: 'Has no date', scheduled_date: '' },
    { id: 'p_cal_settings', name: '__cal_settings__', caption: '{"collab_mode":true}', scheduled_date: '2026-08-12' },
    { id: 'self', name: 'Video 5', caption: 'The card itself', scheduled_date: '2026-08-12' },
  ];
  const opts = { cardDate: '2026-09-30', createdAt: '2026-09-28T22:00:00Z', excludeIds: ['self'] };
  eq(L.selectEarlierCaptioned(rows, opts).map((r) => r.id), ['a2', 'a1'], 'newest first; old, later, blank, undated, settings and the card itself are not evidence');
  eq(L.selectEarlierCaptioned(rows, { ...opts, cardDate: '' }).map((r) => r.id), ['a2', 'a1'], 'no card date: the day the thumbnail was queued is the limit');
  eq(L.selectEarlierCaptioned(rows, { ...opts, cardDate: '2026-08-05' }).map((r) => r.id), ['a1'], 'only what is scheduled before the card');
  eq(L.selectEarlierCaptioned(rows, { createdAt: '2026-09-28T22:00:00Z', excludeIds: ['self'] }).length, 2, 'cardDate may be omitted');
  eq(L.selectEarlierCaptioned(rows, { cardDate: '2026-09-30' }), [], 'no creation date: nothing is evidence');
  eq(L.selectEarlierCaptioned(null, opts), [], 'no rows');
  const many = Array.from({ length: 60 }, (_v, i) => ({ id: 'm' + i, name: 'x', caption: 'cap ' + i, scheduled_date: '2026-08-' + String(1 + (i % 28)).padStart(2, '0') }));
  eq(L.selectEarlierCaptioned(many, opts).length, L.BORROWED_MAX_CAPTIONS, 'capped');
  eq(L.selectEarlierCaptioned([{ id: 'l', name: 'x', caption: 'y'.repeat(2000), scheduled_date: '2026-08-04' }], opts)[0].caption.length, L.BORROWED_CAPTION_CHARS, 'long captions are cut');

  // --- Reading the model's answer ---------------------------------------------------------------------
  const read = L.parseCheck(answer({ earlier: [{ key: 'c1', video: 1 }, { key: 'c2', video: null }, { key: 'c3', video: 'unsure' }], new: [{ key: 'p1', video: 7 }, { key: 'zz', video: 3 }] }), 3, ['p1', 'p2']);
  eq([read.ok, read.earlier, [...read.targets]], [true, [1, null, 'unsure'], [['p1', 7]]], 'numbers, null and unsure are kept; unknown keys are ignored');
  eq(L.parseCheck(answer({ earlier: [{ key: 'c1', video: 2 }] }), 3, []).earlier, [2, 'unsure', 'unsure'], 'a caption the model left out is unsure');
  eq(L.parseCheck(answer({ earlier: [{ key: 'c1', video: 'five' }, { key: 'c2', video: 0 }, { key: 'c9', video: 4 }] }), 2, []).earlier, ['unsure', 'unsure'], 'junk values and out-of-range keys are unsure');
  eq(L.parseCheck([{ type: 'text', text: 'Here you go:\n```json\n{"earlier":[{"key":"c1","video":3}],"new":[]}\n```' }], 1, []).earlier, [3], 'fenced JSON is read');
  eq(L.parseCheck([{ type: 'text', text: 'Sure! {"earlier":[{"key":"c1","video":3}]} Hope that helps' }], 1, []).earlier, [3], 'JSON inside prose is read');
  eq(L.parseCheck([{ type: 'text', text: 'no idea' }], 1, []).error, 'check_not_json', 'prose only: not read');
  eq(L.parseCheck([], 1, []).error, 'check_empty', 'nothing back');
  eq(L.parseCheck(answer([1, 2]), 1, []).ok, false, 'an array is not the answer shape');
  const msg = L.checkMessage([{ caption: 'First caption' }, { caption: 'Second caption' }], [{ key: 'p1', videoNumber: 5, postName: 'Video 5' }, { key: 'p2' }], 'THE PLAN');
  ok(msg.includes('"key":"c1"') && msg.includes('"key":"c2"') && msg.includes('First caption') && msg.includes('"videoNumber":5') && msg.endsWith('THE PLAN'), 'the check message carries the captions, the posts and the plan');
  ok(!/"name"|Video 1\b/.test(L.checkMessage([{ id: 'a1', name: 'Video 1', caption: 'c' }], [], 'p')), 'earlier post names and ids are not sent: topic is the only evidence');
  ok(/never guess/i.test(L.CHECK_SYSTEM_PROMPT) && /unsure/.test(L.CHECK_SYSTEM_PROMPT), 'the check prompt forbids guessing');

  // --- Rules 1 to 3: the verdict ------------------------------------------------------------------------
  const check = (earlier, targets = {}) => ({ ok: true, earlier, targets: new Map(Object.entries(targets)), error: '' });
  const v = (post, c, n) => L.borrowedVerdict({ key: 'p1', ...post }, c, n);

  // Rule 1: used.
  let r = v({ videoNumber: 5 }, check([1, 2, 5]), 3);
  eq([r.accept, r.outcome, r.video], [false, 'borrowed_video_used', 5], 'video 5 was used by an earlier caption: not titled');
  r = v({ postName: 'Bread' }, check([1, 2], { p1: 2 }), 2);
  eq([r.accept, r.outcome], [false, 'borrowed_video_used'], 'a post matched by name to a used video: not titled');
  r = v({ videoNumber: 5 }, check([1, 5, 5, null]), 4);
  eq(r.outcome, 'borrowed_video_used', 'used twice is still used');

  // Rule 2: clearly unused.
  r = v({ videoNumber: 5 }, check([1, 2, 3, 4]), 4);
  eq([r.accept, r.video], [true, 5], 'videos 1 to 4 used, the card says 5: titled');
  r = v({ postName: 'Sourdough' }, check([1, 2, null], { p1: 6 }), 3);
  eq(r.accept, true, 'matched by name to an unused video: titled');
  r = v({ videoNumber: 3 }, check([1, null, 4, null]), 4);
  eq(r.accept, true, 'captions that match no video (null) are not a reason to stop');

  // Rule 3: cannot tell.
  r = v({ videoNumber: 5 }, check([]), 0);
  eq([r.accept, r.outcome, r.why], [false, 'borrowed_unclear', 'no_earlier_captions'], 'no earlier captions at all: cannot tell');
  r = v({ videoNumber: 5 }, check([1, 'unsure', 3]), 3);
  eq([r.accept, r.outcome, r.why], [false, 'borrowed_unclear', 'earlier_unclear'], 'one earlier caption the model could not place: cannot tell');
  r = v({ videoNumber: 5 }, check([null, null]), 2);
  eq([r.accept, r.outcome, r.why], [false, 'borrowed_unclear', 'no_link_to_tab'], 'no earlier caption belongs to this tab: no evidence it is in use');
  r = v({}, check([1, 2]), 2);
  eq([r.accept, r.outcome, r.why], [false, 'borrowed_unclear', 'video_unknown'], 'the post names no video and the model found none: cannot tell');
  r = v({ postName: 'Something' }, check([1, 2], {}), 2);
  eq(r.accept, false, 'a name the model could not place is not guessed');

  // --- The function is wired as the rules need --------------------------------------------------------------
  const fn = fs.readFileSync(path.join(ROOT, 'supabase/functions/thumbnail-titles/index.ts'), 'utf8');
  ok(/const borrowed = posts\.filter\(\(p\) => p\.via\)/.test(fn), 'only posts that borrowed a tab are checked');
  ok(/borrowedVerdict\(p, check, earlier\.length\)/.test(fn) && /if \(verdict\.accept\) continue;/.test(fn), 'the verdict decides before any title is asked for');
  ok(/"needs_info", verdict\.outcome, note\)/.test(fn), 'a refused post is written as needs_info with the new outcome and the borrowed-tab note');
  ok(/for \(const p of borrowed\) await fail\(db, p\.job, error/.test(fn), 'a failed check goes back in the queue and is never read as accepted');
  ok(/toTitle = posts\.filter\(\(p\) => !p\.via\)/.test(fn), 'when the check fails, own-month posts are still titled');
  ok(/askClaude\(apiKey, model, prompt, toTitle, tab\.text\)/.test(fn), 'the title request holds only the accepted posts');
  ok(/post\.via \? borrowedPlanName\(post\.createdAt, post\.via\) : ""/.test(fn), 'the label names the plan only for a borrowed tab');
  ok(/\.eq\("client", slug\)/.test(fn.slice(fn.indexOf('const borrowed ='), fn.indexOf('await askCheck(apiKey'))), 'the earlier captions are read for this client only');
  ok(/callClaude\(apiKey, model, \[\{ role: "user", content: checkMessage/.test(fn) && /CHECK_SYSTEM_PROMPT/.test(fn), 'the check is one extra request with its own prompt');
  ok(!/\.(update|insert|delete|upsert)\(/.test(fn.slice(fn.indexOf('const borrowed ='), fn.indexOf('askClaude(apiKey, model, prompt, toTitle'))), 'the check reads calendar_posts and never writes it');

  console.log(`thumbnail-borrowed-tab: ${checks} checks passed`);
})().catch((e) => { console.error(e); process.exit(1); });
